CREATE TABLE customer_accounts (
    account_id UUID PRIMARY KEY,
    customer_id UUID NOT NULL,
    nickname VARCHAR(80) NOT NULL,
    masked_account_number VARCHAR(32) NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_customer_accounts_customer_id ON customer_accounts(customer_id);
CREATE INDEX idx_customer_accounts_customer_account ON customer_accounts(customer_id, account_id);

CREATE TABLE merchants (
    id UUID PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    normalized_name VARCHAR(160) NOT NULL,
    merchant_category_code VARCHAR(16),
    category VARCHAR(40) NOT NULL,
    city VARCHAR(80),
    state VARCHAR(40),
    country VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);

CREATE INDEX idx_merchants_normalized_name ON merchants(normalized_name);
CREATE INDEX idx_merchants_category ON merchants(category);

CREATE TABLE bank_transactions (
    id UUID PRIMARY KEY,
    source_reference VARCHAR(120) NOT NULL,
    customer_id UUID NOT NULL,
    account_id UUID NOT NULL,
    merchant_id UUID,
    status VARCHAR(20) NOT NULL,
    direction VARCHAR(20) NOT NULL,
    type VARCHAR(30) NOT NULL,
    category VARCHAR(40) NOT NULL,
    description VARCHAR(240) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    authorized_at TIMESTAMP WITH TIME ZONE NOT NULL,
    posted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uk_bank_transactions_source_reference UNIQUE(source_reference),
    CONSTRAINT chk_bank_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_bank_transactions_posted_at CHECK (
        (status = 'PENDING' AND posted_at IS NULL)
        OR (status IN ('POSTED', 'REVERSED') AND posted_at IS NOT NULL)
    )
);

CREATE INDEX idx_bank_transactions_customer_id ON bank_transactions(customer_id);
CREATE INDEX idx_bank_transactions_account_id ON bank_transactions(account_id);
CREATE INDEX idx_bank_transactions_status ON bank_transactions(status);
CREATE INDEX idx_bank_transactions_authorized_at ON bank_transactions(authorized_at);
CREATE INDEX idx_bank_transactions_posted_at ON bank_transactions(posted_at);
CREATE INDEX idx_bank_transactions_category ON bank_transactions(category);
CREATE INDEX idx_bank_transactions_merchant_id ON bank_transactions(merchant_id);
CREATE INDEX idx_bank_transactions_customer_account_authorized ON bank_transactions(customer_id, account_id, authorized_at DESC);
CREATE INDEX idx_bank_transactions_customer_authorized ON bank_transactions(customer_id, authorized_at DESC);

CREATE TABLE transaction_outbox (
    id UUID PRIMARY KEY,
    aggregate_id UUID NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL,
    correlation_id VARCHAR(120),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_transaction_outbox_status_next_attempt ON transaction_outbox(status, next_attempt_at);
CREATE INDEX idx_transaction_outbox_aggregate_id ON transaction_outbox(aggregate_id);

